
import shutil, time, sys
def patch(path, reps, tag):
    s=open(path,encoding='utf-8').read(); orig=s; missing=[]
    for a,b in reps:
        if a not in s: missing.append(a[:30])
        s=s.replace(a,b)
    if s!=orig:
        shutil.copyfile(path,path+'.bak-'+tag+'-'+time.strftime('%Y%m%d-%H%M%S'))
        open(path,'w',encoding='utf-8').write(s)
    print(path,'changed' if s!=orig else 'nochange','missing',missing)

